-- api_user solo puede ejecutar Functions del schema api.
-- No tiene SELECT/INSERT/UPDATE/DELETE sobre tablas.

REVOKE ALL ON SCHEMA negocio FROM api_user;
REVOKE ALL ON ALL TABLES IN SCHEMA negocio FROM api_user;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA negocio FROM api_user;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA negocio FROM api_user;

GRANT USAGE ON SCHEMA api TO api_user;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA api TO api_user;

ALTER DEFAULT PRIVILEGES IN SCHEMA api
    GRANT EXECUTE ON FUNCTIONS TO api_user;

ALTER DEFAULT PRIVILEGES IN SCHEMA negocio
    REVOKE ALL ON TABLES FROM api_user;

ALTER DEFAULT PRIVILEGES IN SCHEMA negocio
    REVOKE ALL ON FUNCTIONS FROM api_user;
